"""The site's Markdown, for the repo's own docs: what they use, turned into HTML."""

from pcs14.site import markdown


def html(text, **kw):
    return markdown.to_html(text, **kw)


def test_headings_get_ids_github_would_give_them():
    out = html("# The verdict\n\n## What it can't prove")
    assert '<h1 id="the-verdict">The verdict</h1>' in out
    assert '<h2 id="what-it-cant-prove">What it can&#x27;t prove</h2>' in out


def test_paragraphs_join_their_lines_and_escape_html():
    out = html("A line\nand the next, with <angle> & amp.\n\nA new one.")
    assert "<p>A line\nand the next, with &lt;angle&gt; &amp; amp.</p>" in out
    assert "<p>A new one.</p>" in out


def test_inline_marks_links_and_images():
    out = html("**bold**, *italic*, `code *not italic*`, [a link](x.md#top) and ![a still](s.png)")
    assert "<strong>bold</strong>" in out and "<em>italic</em>" in out
    assert "<code>code *not italic*</code>" in out
    assert '<a href="x.md#top">a link</a>' in out
    assert '<img src="s.png" alt="a still">' in out


def test_links_and_images_go_through_the_rewriters():
    out = html(
        "[doc](../log/x.md) ![p](stills/a.png)", link=lambda u: "L:" + u, image=lambda u: "I:" + u
    )
    assert 'href="L:../log/x.md"' in out and 'src="I:stills/a.png"' in out


def test_tables_with_inline_marks_and_a_line_break():
    out = html("| Part | Note |\n|---|---|\n| **Motor**<br>Emax | four |\n| Prop | `x` |")
    assert "<table>" in out and "<th>Part</th>" in out
    assert "<td><strong>Motor</strong><br>Emax</td>" in out and "<td><code>x</code></td>" in out


def test_lists_numbered_lists_and_a_nested_one():
    out = html("- one\n- two\n  - two a\n\n1. first\n2. second")
    assert "<ul><li>one</li><li>two<ul><li>two a</li></ul></li></ul>" in out.replace("\n", "")
    assert "<ol><li>first</li><li>second</li></ol>" in out.replace("\n", "")


def test_code_blocks_stay_as_written():
    out = html("```bash\nmake -C x <target> && go\n```")
    code = "make -C x &lt;target&gt; &amp;&amp; go"
    assert f'<pre><code class="language-bash">{code}</code></pre>' in out


def test_details_blocks_and_rules_pass_through():
    out = html(
        "<details>\n<summary>connector current: 51 checked</summary>\n\n"
        "| a |\n|---|\n| b |\n\n</details>\n\n---"
    )
    assert "<details>" in out and "<summary>connector current: 51 checked</summary>" in out
    assert "<td>b</td>" in out and "</details>" in out and "<hr>" in out


def test_a_quote_and_checkboxes():
    out = html("> said once\n\n- [ ] **Read:** a book")
    assert "<blockquote><p>said once</p></blockquote>" in out.replace("\n", "")
    assert '<li><input type="checkbox" disabled> <strong>Read:</strong> a book</li>' in out


def test_an_italic_line_with_code_in_it():
    out = html("*Generated by `pcs14 site`, from `docs/`.*")
    assert (
        out.strip()
        == "<p><em>Generated by <code>pcs14 site</code>, from <code>docs/</code>.</em></p>"
    )
