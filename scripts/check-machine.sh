#!/usr/bin/env bash
# What does this machine have, as far as this project cares?
# Read-only: it checks things, it never installs anything.
#
#   scripts/check-machine.sh          print the report
#   scripts/check-machine.sh pc       print it and save it to docs/machines/pc.md
#
# Works on native Ubuntu 24.04 (the PC) and WSL2 (the laptop). It leaves out
# anything personal (hostname, username, email, paths in my home folder),
# because the report gets committed to a public repo.

set -u

name="${1:-}"
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

have() { command -v "$1" >/dev/null 2>&1; }
first_line() { head -n1 | sed 's/[[:space:]]*$//'; }
or_missing() { if [ -n "$1" ]; then echo "$1"; else echo "not installed"; fi; }

# --- System ---------------------------------------------------------------

os="$(. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME")"
kernel="$(uname -r)"
if grep -qi microsoft /proc/version 2>/dev/null; then env_kind="WSL2"; else env_kind="native Linux"; fi
cpu="$(lscpu 2>/dev/null | sed -n 's/^Model name:[[:space:]]*//p' | first_line)"
threads="$(nproc)"
ram_gb="$(free -g | awk '/^Mem:/ {print $2}')"
disk_free="$(df -h --output=avail "$repo_root" | tail -n1 | tr -d ' ')"

if have nvidia-smi; then
  gpu="$(nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader 2>/dev/null | first_line)"
  [ -n "$gpu" ] || gpu="nvidia-smi is installed but can't see a GPU"
elif have lspci; then
  gpu="$(lspci | grep -iE 'vga|3d|display' | sed 's/^[^:]*: //' | first_line) (no NVIDIA driver)"
else
  gpu="unknown (no nvidia-smi or lspci)"
fi

if have glxinfo; then
  opengl="$(glxinfo -B 2>/dev/null | sed -n 's/^OpenGL renderer string: //p' | first_line)"
  [ -n "$opengl" ] || opengl="glxinfo can't open a display"
else
  opengl="unknown (install mesa-utils for glxinfo)"
fi

if [ -d /mnt/wslg ]; then display="WSLg"; else display="${XDG_SESSION_TYPE:-none detected}"; fi

# --- Tools -----------------------------------------------------------------

git_v="$(have git && git --version | first_line)"
lfs_v="$(have git-lfs && git lfs version 2>/dev/null | awk '{print $1}')"
gh_v="$(have gh && gh --version | first_line)"
if have gh && gh auth status >/dev/null 2>&1; then gh_auth="logged in"; else gh_auth="not logged in"; fi
git_name="$(git config --global user.name 2>/dev/null)"
if git config --global user.email >/dev/null 2>&1; then git_email="set"; else git_email="not set"; fi

py_v="$(have python3 && python3 --version 2>&1)"
if python3 -c 'import ensurepip' 2>/dev/null; then venv_ok="yes"; else venv_ok="no (sudo apt install python3-venv)"; fi
if [ -x "$repo_root/.venv/bin/python" ]; then project_venv="yes (.venv)"; else project_venv="not yet (run scripts/setup-dev.sh)"; fi

# --- Simulation toolchain (installed later by scripts/setup-ubuntu.sh) ------

gz_v="$(have gz && gz sim --versions 2>/dev/null | first_line)"
foam_v="$( (have simpleFoam && echo "found (simpleFoam on PATH)") || true)"
pv_v="$(have pvpython && pvpython --version 2>/dev/null | first_line)"
blender_v="$(have blender && blender --version 2>/dev/null | first_line)"
px4_v="$( [ -d "$HOME/PX4-Autopilot" ] && echo "found (~/PX4-Autopilot)" )"

# --- Report ----------------------------------------------------------------

report="$(cat <<EOF
# Machine check${name:+: $name}

Generated by \`scripts/check-machine.sh\` on $(date -u +%Y-%m-%d). Read-only; nothing was installed.

## System

| | |
|---|---|
| OS | ${os:-unknown} |
| Kernel | $kernel |
| Environment | $env_kind |
| CPU | ${cpu:-unknown} ($threads threads) |
| RAM | ${ram_gb} GB visible to Linux |
| Free disk (where the repo is) | $disk_free |
| GPU | $gpu |
| OpenGL renderer | $opengl |
| Display | $display |

## Tools

| | |
|---|---|
| git | $(or_missing "$git_v") |
| Git LFS | $(or_missing "$lfs_v") |
| GitHub CLI | $(or_missing "$gh_v"), $gh_auth |
| git name | ${git_name:-not set} |
| git email | $git_email |
| Python | $(or_missing "$py_v") |
| Can make venvs | $venv_ok |
| Project venv | $project_venv |

## Simulation toolchain

Not expected yet. \`scripts/setup-ubuntu.sh\` will install these.

| | |
|---|---|
| Gazebo | $(or_missing "$gz_v") |
| PX4 | $(or_missing "$px4_v") |
| OpenFOAM | $(or_missing "$foam_v") |
| ParaView | $(or_missing "$pv_v") |
| Blender | $(or_missing "$blender_v") |
EOF
)"

echo "$report"

if [ -n "$name" ]; then
  out="$repo_root/docs/machines/$name.md"
  mkdir -p "$(dirname "$out")"
  printf '%s\n' "$report" > "$out"
  echo
  echo "Saved to docs/machines/$name.md. Commit it so the other machine can see it."
fi
